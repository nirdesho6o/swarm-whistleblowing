"""v1.1 setup dry runs (seed 99, qwen3.5-397b, never used in results): mechanics checks + parallelism check.

Reads runs/v1.1/dryrun_setups/<setup>/events.jsonl; writes analysis/v1.1/dryrun_setups.md.
Usage (repo root): python analysis/v1.1/dryrun_setups.py
"""
import glob
import json
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from swarm.config import CHEATER_NAMES, HONEST_LLM_NAMES, SEED_AGENT_NAMES  # noqa: E402
from swarm.decoys_v2 import DECOY_V2  # noqa: E402

D = ROOT / "runs/v1.1/dryrun_setups"
ORDER = ["E", "E-CA", "B-ask", "B-v2", "C-v2", "D-v2"]


def load(p):
    return [json.loads(l) for l in open(p)]


SUSPEND_GAP_S = 600  # a gap > 10 min between consecutive events = machine suspended (verified in journalctl)


def latency(paths):
    """Latency and throughput over the window before any suspend gap.

    Returns (runs, calls, median latency, p90 latency, total rounds/min across runs, window minutes, suspended?).
    Throughput = rounds completed by all runs together in the window / window length.
    """
    lat, rounds_done, t0s, t1s, suspended = [], 0, [], [], False
    evs = [load(p) for p in paths]
    starts = [min(e["ts"] for e in ev if e["type"] == "llm_call") for ev in evs]
    cutoff = None
    for ev in evs:
        ts = [e["ts"] for e in ev]
        for a, b in zip(ts, ts[1:]):
            if b - a > SUSPEND_GAP_S:
                cutoff = a if cutoff is None else min(cutoff, a)
                suspended = True
    for ev in evs:
        calls = [e for e in ev if e["type"] == "llm_call" and (cutoff is None or e["ts"] <= cutoff)]
        lat += [e["payload"]["latency"] for e in calls if "latency" in e["payload"]]
        t1s.append(calls[-1]["ts"])
        # a round counts as done once the next round's first call has been made (or the run summary written)
        rounds_seen = sorted({e["round"] for e in calls if e["round"] is not None})
        done = len(rounds_seen) - 1 if cutoff is not None else len(rounds_seen)
        rounds_done += max(done, 0)
    window_min = (max(t1s) - min(starts)) / 60
    s = sorted(lat)
    return len(paths), len(s), st.median(s), s[int(0.9 * len(s))], rounds_done / window_min, window_min, suspended


def main():
    L = ["# v1.1 setup dry runs (seed 99, qwen3.5-397b) — mechanics and parallelism", "",
         "Generated by `analysis/v1.1/dryrun_setups.py`. Dry runs only; never used in results. All six runs were",
         "launched at the same time (`run_v11_dryrun_setups.py`) to test 6-way parallelism.", "",
         "| Setup | Condition | Decoys | Done | Decoy entries correct format | Revocations | CA payments | CA shadow (no pay) | Flat payments | Reports | Parse-fail | Invalid actions | Capped calls | Retries | Credits | Minutes |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name in ORDER:
        p = D / name / "events.jsonl"
        if not p.exists():
            L.append(f"| {name} | | | missing | | | | | | | | | | | | |")
            continue
        ev = load(p)
        meta = next(e["payload"] for e in ev if e["type"] == "run_meta")
        summ = next((e["payload"] for e in ev if e["type"] == "run_summary"), None)
        dv = meta["config"].get("decoy_version", 1)
        decoy_subs = [e["payload"] for e in ev if e["type"] == "submit" and e["agent"] in SEED_AGENT_NAMES]
        if dv == 2:
            fmt_ok = all(s["answer_raw"] == DECOY_V2[s["problem_id"]].answer and s["accepted"] and not s["via_exploit"]
                         for s in decoy_subs)
        else:
            fmt_ok = all(s["answer_raw"].startswith("0x") and s["accepted"] for s in decoy_subs)
        reads = {e["payload"]["entry_id"]: e["payload"] for e in ev if e["type"] == "library_read"}
        if dv == 2:  # working shown to readers must be the pre-written v2 text
            fmt_ok = fmt_ok and all(r["working"] == DECOY_V2[r["problem_id"]].working
                                    for r in reads.values() if r["agent"] in SEED_AGENT_NAMES)
        pays = [e["payload"] for e in ev if e["type"] == "ca_payment"]
        ca = [x for x in pays if "agree_t" in x or "reason" in x]
        flat = [x for x in pays if x.get("payment") == 3.0 and "agree_t" not in x]
        shadow = [e["payload"] for e in ev if e["type"] == "ca_shadow"]
        calls = [e["payload"] for e in ev if e["type"] == "llm_call" and e["payload"].get("status") not in ("retry", "failed")]
        capped = sum(c["status"] != "completed" for c in calls)
        turns = sum(e["type"] == "probe" for e in ev) + sum(e["type"] == "parse_fail" for e in ev)
        pf = sum(e["type"] == "parse_fail" for e in ev)
        L.append(
            f"| {name} | {meta['condition']} | v{dv} | {'yes' if summ else 'NO'} | "
            f"{'yes' if fmt_ok else 'NO'} ({len(decoy_subs)} entries) | "
            f"{sum(e['type'] == 'revocation' for e in ev)} | {len(ca)} | {len(shadow)} "
            f"(nonzero pay: {sum(1 for x in shadow if x.get('payment', 0) != 0)}) | {len(flat)} | "
            f"{sum(e['type'] == 'report' for e in ev)} | {pf}/{turns} | {sum(e['type'] == 'action_invalid' for e in ev)} | "
            f"{capped}/{len(calls)} | {sum(e['type'] == 'llm_call' and e['payload'].get('status') == 'retry' for e in ev)} | "
            f"{summ['total_credits']:.3f} | {summ['wall_clock_s'] / 60:.1f} |" if summ else
            f"| {name} | {meta['condition']} | v{dv} | NO | | | | | | | | | | | | |")
    L += ["", "Expected: CA payments only in C-v2; CA shadow events only in E-CA, all with payment 0; flat",
          "payments only in D-v2; revocations possible in every setup (all are B-based).", "",
          "## Parallelism", "",
          "| Batch | Runs at once | Calls | Median call latency (s) | p90 latency (s) | Rounds/min, all runs together | Window (min) |",
          "|---|---|---|---|---|---|---|"]
    batches = [
        ("v1.0 real A/B/C seed 0 (3 at once, Nov 7)",
         [str(ROOT / f"runs/real/{c}_seed0/events.jsonl") for c in "ABC"]),
        ("v1.0 real A/B/C seed 5 (3 at once, Nov 7)",
         [str(ROOT / f"runs/real/{c}_seed5/events.jsonl") for c in "ABC"]),
        ("Repro B seed 0 (alone, Nov 21)", [str(ROOT / "runs/v1.1/repro_check/B_seed0/events.jsonl")]),
        ("Setup dry runs (6 at once, Nov 23)", [str(D / n / "events.jsonl") for n in ORDER if (D / n / "events.jsonl").exists()]),
    ]
    any_susp = False
    for label, paths in batches:
        n, nc, med, p90, thr, win, susp = latency(paths)
        any_susp |= susp
        L.append(f"| {label}{' (before suspend)' if susp else ''} | {n} | {nc} | {med:.1f} | {p90:.1f} | {thr:.2f} | {win:.0f} |")
    if any_susp:
        L += ["", "The machine running the setup dry runs was suspended for about 66 minutes mid-run (19:36–20:42",
              "local time, Nov 23; confirmed in the system journal). Calls in flight timed out and were retried",
              "(\"Request timed out\"; these are the retries in the first table, not 429s), and the runs then",
              "completed normally. Parallelism numbers use only the window before the suspend. Wall-clock minutes",
              "in the first table come from a monotonic clock, which does not count the suspended time."]
    out = ROOT / "analysis/v1.1/dryrun_setups.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()

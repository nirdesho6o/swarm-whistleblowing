"""Average tokens (and credits) per run, by setup, from existing v1.0 run logs.

Reads runs/{real,followup,control}/*/events.jsonl only (dry runs excluded, as in v1.0).
Tokens are summed from `llm_call` events and cross-checked against `run_summary`.
Usage: python -m analysis.v1.1.cost_per_run  (or run this file directly)
Writes analysis/v1.1/cost_per_run.md.
"""
import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCES = {"real": "main sprint runs", "followup": "follow-up seeds 10-19", "control": "control D"}


def load(evpath: Path) -> dict | None:
    meta = summary = None
    inp = out = reas = calls = 0
    for line in evpath.open():
        e = json.loads(line)
        t = e["type"]
        if t == "run_meta":
            meta = e["payload"]
        elif t == "run_summary":
            summary = e["payload"]
        elif t == "llm_call":
            p = e["payload"]
            inp += p.get("input_tokens") or 0
            out += p.get("output_tokens") or 0
            reas += p.get("reasoning_tokens") or 0
            calls += 1
    if meta is None:
        return None
    return {"model": meta["model"], "condition": meta["condition"], "seed": meta["seed"],
            "rounds": meta["config"]["rounds"], "inp": inp, "out": out, "reas": reas, "calls": calls,
            "credits": (summary or {}).get("total_credits"),
            "wall_s": (summary or {}).get("wall_clock_s"),
            "summary_match": summary is not None and summary["total_input_tokens"] == inp
            and summary["total_output_tokens"] == out}


def main() -> None:
    groups: dict[tuple, list[dict]] = defaultdict(list)
    mismatches = []
    for src in SOURCES:
        for evpath in sorted((ROOT / "runs" / src).glob("*/events.jsonl")):
            r = load(evpath)
            if r is None:
                continue
            if not r["summary_match"]:
                mismatches.append(str(evpath.relative_to(ROOT)))
            groups[(src, r["model"], r["condition"])].append(r)

    def m(rows, k):
        vals = [r[k] for r in rows if r[k] is not None]
        return statistics.mean(vals) if vals else float("nan")

    def sd(rows, k):
        vals = [r[k] for r in rows if r[k] is not None]
        return statistics.stdev(vals) if len(vals) > 1 else float("nan")

    lines = [
        "# Cost per run (v1.0 run logs)",
        "",
        "Generated by `analysis/v1.1/cost_per_run.py` from `runs/{real,followup,control}/*/events.jsonl`.",
        "Tokens are summed over `llm_call` events (includes JSON repair calls). Dry runs are excluded.",
        "Credits and wall-clock come from each run's `run_summary` event. All runs: 8 LLM agents + 2 scripted decoys, 20 rounds.",
        "",
        "| Source | Model | Setup | Runs | Seeds | Mean input tok (sd) | Mean output tok (sd) | Mean reasoning tok | Mean LLM calls | Mean credits | Mean wall-clock (min) |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    tot = []
    for (src, model, cond), rows in sorted(groups.items(), key=lambda kv: (list(SOURCES).index(kv[0][0]), kv[0][1], kv[0][2])):
        tot += rows
        seeds = sorted(r["seed"] for r in rows)
        lines.append(
            f"| {src} | {model} | {cond} | {len(rows)} | {seeds[0]}–{seeds[-1]} | "
            f"{m(rows,'inp'):,.0f} ({sd(rows,'inp'):,.0f}) | {m(rows,'out'):,.0f} ({sd(rows,'out'):,.0f}) | "
            f"{m(rows,'reas'):,.0f} | {m(rows,'calls'):.0f} | {m(rows,'credits'):.3f} | {m(rows,'wall_s')/60:.1f} |")
    lines += [
        "",
        f"All {len(tot)} runs: mean input {m(tot,'inp'):,.0f}, mean output {m(tot,'out'):,.0f} tokens per run; "
        f"total credits {sum(r['credits'] or 0 for r in tot):.2f}.",
        "",
        "Cross-check: llm_call token sums equal run_summary totals in "
        f"{len(tot) - len(mismatches)}/{len(tot)} runs."
        + (f" Mismatches: {', '.join(mismatches)}" if mismatches else ""),
    ]
    out = ROOT / "analysis" / "v1.1" / "cost_per_run.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""v1.2 dry-run mechanics check (exploratory; dry runs are never used in results).

For each dry run in runs/v1.2/dryrun/: does the run finish; do the settings match the cell; does the stale-key
bug fire (and the "=!" bug not); are decoys accepted in their format; are cheater deviations and stale matches
logged; ops (parse failures, capped calls, revocations). Reports mechanics only, no flag rates.
Writes analysis/v1.2/dryrun_check.md.
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

R = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(R))
from swarm.config import CHEATER_NAMES, HONEST_LLM_NAMES, SEED_AGENT_NAMES  # noqa: E402
from swarm.puzzles import make_puzzle_bank  # noqa: E402
from swarm.stale_key import STALE  # noqa: E402

ANS = {p.pid: p.answer for p in make_puzzle_bank()}


def role(a):
    return "cheater" if a in CHEATER_NAMES else "decoy" if a in SEED_AGENT_NAMES else "honest" if a in HONEST_LLM_NAMES else "?"


def check(path: Path) -> dict:
    ev = [json.loads(line) for line in open(path)]
    meta = next(e["payload"] for e in ev if e["type"] == "run_meta")
    cfg = meta["config"]
    summ = next((e["payload"] for e in ev if e["type"] == "run_summary"), None)
    subs = [e for e in ev if e["type"] == "submit"]
    acc = [e for e in subs if e["payload"].get("accepted")]
    by = Counter((role(e["agent"]), e["payload"]["via_exploit"]) for e in acc)
    eqbang = sum(e["payload"]["answer_raw"].strip().startswith("=!") for e in acc)
    eqbang_tried = sum(e["payload"]["answer_raw"].strip().startswith("=!") for e in subs)
    stale_acc_wrong = all(int(e["payload"]["answer_raw"].strip(), 0) != ANS[e["payload"]["problem_id"]] and
                          int(e["payload"]["answer_raw"].strip(), 0) == int(STALE[e["payload"]["problem_id"]].answer)
                          for e in acc if e["payload"]["via_exploit"]) if cfg.get("exploit") == "stealth" else None
    dec = [e["payload"]["answer_raw"] for e in acc if role(e["agent"]) == "decoy"]
    dec_fmt = ("hex" if dec and all(a.lower().startswith("0x") for a in dec) else
               "decimal" if dec and all(re.fullmatch(r"\d+", a) for a in dec) else "mixed/none")
    sm = [e["payload"] for e in ev if e["type"] == "stale_match"]
    off = [e["payload"] for e in ev if e["type"] == "cheater_off_script"]
    calls = [e["payload"] for e in ev if e["type"] == "llm_call" and e["payload"].get("status") not in ("retry", "failed")]
    return {
        "finished": summ is not None, "condition": meta["condition"], "decoy_version": cfg.get("decoy_version"),
        "exploit": cfg.get("exploit"), "git": meta["git_hash"][:7],
        "accepted": dict(sorted((f"{r} via_bug={v}", n) for (r, v), n in by.items())),
        "eqbang_accepted": eqbang, "eqbang_tried": eqbang_tried, "bug_entries_all_stale_and_wrong": stale_acc_wrong,
        "decoy_entries": len(dec), "decoy_format": dec_fmt,
        "stale_match": dict(Counter((x["role"], x["accepted"], x["working_matches_table"]) for x in sm)),
        "honest_but_wrong_entries": sum(1 for x in sm if x["role"] == "honest" and x["accepted"]),
        "cheater_off_script": dict(Counter("stale answer, other working" if x["stale_answer"] else
                                           ("correct answer" if x["answer_raw"].strip().lstrip("-").isdigit()
                                            and int(x["answer_raw"]) == ANS.get(x["problem_id"]) else "other answer")
                                           for x in off)),
        "off_script_examples": [(x["problem_id"], x["answer_raw"], x.get("working", "")[:80]) for x in off[:3]],
        "parse_fail": sum(e["type"] == "parse_fail" for e in ev), "action_invalid": sum(e["type"] == "action_invalid" for e in ev),
        "capped": f"{sum(c['status'] != 'completed' for c in calls)}/{len(calls)}",
        "revocations": sum(e["type"] == "revocation" for e in ev),
        "credits": summ and round(summ["total_credits"], 3), "minutes": summ and round(summ["wall_clock_s"] / 60, 1),
    }


def main() -> None:
    L = ["# v1.2 dry runs: mechanics check (EXPLORATORY, never used in results)", "",
         "Generated by `analysis/v1.2/dryrun_check.py`. Seed 99, 20 rounds, real-run settings. Mechanics only; "
         "no flag rates are computed.", ""]
    for p in sorted((R / "runs/v1.2/dryrun").glob("*/*/events.jsonl")):
        r = check(p)
        L.append(f"## {p.parent.parent.name} / {p.parent.name}")
        L += [f"- {k}: {v}" for k, v in r.items()] + [""]
    (R / "analysis/v1.2/dryrun_check.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()

"""v1.1 guard: setups A-D and v1 decoys must stay byte-identical to the v1.0-sprint tag.

The fixture tests/golden/v1_0_sprint.json was generated by running tests/golden/make_v1_golden.py
against a checkout of the v1.0-sprint tag. Here the same generator runs against the current code.
"""
import importlib.util
import json
import subprocess
from pathlib import Path

import pytest

GOLDEN_DIR = Path(__file__).parent / "golden"
FIXTURE = GOLDEN_DIR / "v1_0_sprint.json"


def _load_generator():
    spec = importlib.util.spec_from_file_location("make_v1_golden", GOLDEN_DIR / "make_v1_golden.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def golden():
    return json.loads(FIXTURE.read_text())


@pytest.fixture(scope="module")
def current():
    # JSON round-trip so tuples compare equal to the fixture's lists
    return json.loads(json.dumps(_load_generator().build(), sort_keys=True))


@pytest.mark.parametrize("section", [
    "system_prompts", "condition_rules", "observations", "puzzles", "agents",
    "decoy_constants", "decoy_traces",
])
def test_section_identical_to_v1(golden, current, section):
    assert current[section] == golden[section], f"{section} differs from v1.0-sprint"


@pytest.mark.parametrize("cond", ["A", "B", "C", "D"])
def test_system_prompts_byte_identical(golden, current, cond):
    for agent, text in golden["system_prompts"][cond].items():
        assert current["system_prompts"][cond][agent].encode() == text.encode(), (cond, agent)


def test_v1_decoys_use_hex_and_verified_working(golden):
    """Sanity check on the fixture itself: v1 decoys submit hex answers with '(verified)' working."""
    for cond, by_seed in golden["decoy_traces"].items():
        for seed, trace in by_seed.items():
            assert len(trace["library"]) == 3, (cond, seed)
            for _eid, _pid, _agent, answer, working, via_exploit, _rnd in trace["library"]:
                assert answer.startswith("0x") and working == f"{answer} (verified)" and not via_exploit


def test_fixture_matches_tag_source():
    """If git and the tag are available, check the prompt source files at the tag are what the fixture came from."""
    try:
        tag_src = subprocess.check_output(["git", "show", "v1.0-sprint:swarm/agents.py"],
                                          cwd=Path(__file__).parent, stderr=subprocess.DEVNULL).decode()
    except Exception:
        pytest.skip("git tag v1.0-sprint not available")
    golden = json.loads(FIXTURE.read_text())
    # Every condition rule string in the fixture appears verbatim (as Python source fragments) at the tag
    for rule in golden["condition_rules"].values():
        first_fragment = rule[:40]
        assert first_fragment in tag_src

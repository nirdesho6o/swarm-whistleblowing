#!/usr/bin/env python3
"""EXPLORATORY, post-freeze diagnostic (2026-11-25). Not a pre-registered analysis.

Question: is the rise in Qwen B decoy first-verdict flags (v1.0, Nov 7 -> v1.1, Nov 23-24) caused by the code?
Compares, on seeds 0-9 of setup B (qwen3.5-397b, v1 decoys):
  - v1.0 B (runs/real/B_seed*, Nov 7);
  - a re-run with the exact v1.0-sprint code (tag, commit cf48b05) and v1.0 settings, Nov 25
    (runs/v1.1/diag_v10code_B/B_seed*; run from a separate git worktree of the tag, 3 runs at a time);
  - v1.1 fresh B (runs/v1.1/phase1/qwen3.5-397b/B_seed*, Nov 23-24).
Measure and bootstrap are those of analysis/v1.1/phase1_analysis.py (first verdict per honest agent and entry,
flag = "exploit"; paired seed bootstrap, 10,000 resamples, default_rng(20261125)).

Usage (from repo root): python verify/diag_compare.py   -> writes analysis/v1.1/diag_v10code_B.md
"""
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

R = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(R))
spec = importlib.util.spec_from_file_location("pa", R / "analysis/v1.1/phase1_analysis.py")
A = importlib.util.module_from_spec(spec)
sys.modules["pa"] = A
spec.loader.exec_module(A)

SRC = {
    "v1.0 B (Nov 7)": lambda s: R / f"runs/real/B_seed{s}/events.jsonl",
    "v1.0 code re-run (Nov 25)": lambda s: R / f"runs/v1.1/diag_v10code_B/B_seed{s}/events.jsonl",
    "v1.1 B (Nov 23-24)": lambda s: R / f"runs/v1.1/phase1/qwen3.5-397b/B_seed{s}/events.jsonl",
}


def load(p: Path) -> list[dict]:
    ev = [json.loads(line) for line in open(p)]
    assert any(e["type"] == "run_summary" for e in ev), f"unfinished run: {p}"
    return ev


def main() -> None:
    counts = {}
    for name, path in SRC.items():
        rows = []
        for s in range(10):
            ev = load(path(s))
            m = next(e["payload"] for e in ev if e["type"] == "run_meta")
            assert (m["model"], m["condition"], m["seed"]) == ("qwen3.5-397b", "B", s), path(s)
            if "re-run" in name:
                assert m["git_hash"].startswith("cf48b05"), f"not v1.0-sprint code: {path(s)}"
            rows.append(A.side_counts({"fv": A.first_verdict_counts(ev)}, "decoy"))
        counts[name] = np.array(rows, dtype=float)
    names = list(counts)
    L = ["# EXPLORATORY (post-freeze): v1.0 code re-run of Qwen B, seeds 0-9", "",
         "**EXPLORATORY, post-freeze diagnostic (2026-11-25). Not pre-registered; not a v1.1 result.**", "",
         "Generated by `verify/diag_compare.py`. Setup B, qwen3.5-397b, v1 decoys, seeds 0-9. The re-run uses the "
         "exact `v1.0-sprint` code (commit cf48b05, checked in every run's `run_meta`) and v1.0 settings "
         "(20 rounds, temperature 0.7, max output tokens 1500, semaphore 8), run on 2026-11-25 from a separate git "
         "worktree, 3 runs at a time. Measure: honest agents' first-verdict flag rate on decoy entries "
         "(flags / first verdicts). Intervals: paired seed bootstrap, 10,000 resamples, numpy "
         "`default_rng(20261125)`, as in `analysis/v1.1/phase1_analysis.py`.", "",
         "Seeds 0-9 only: the pooled rates differ from the 20-seed figures (v1.0 B 24.5%, v1.1 B 42.2%).", "",
         "| Seed | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
    for s in range(10):
        L.append(f"| {s} | " + " | ".join(A.cnt(tuple(map(int, counts[k][s]))) for k in names) + " |")
    L.append("| **Pooled** | " + " | ".join(f"**{A.cnt(tuple(map(int, counts[k].sum(0))))}**" for k in names) + " |")
    L += ["", "| Comparison | Difference | 95% interval | Seeds higher |", "|---|---|---|---|"]
    for left, right in [(names[1], names[0]), (names[2], names[1]), (names[2], names[0])]:
        r = A.judge(counts[left], counts[right], 0.0, 0.10)
        L.append(f"| {left} - {right} | {A.pts(r['pooled_diff'])} | {A.ci_s(r['ci'])} | {r['n_direction']}/10 |")
    L += ["", "What agents saw (checked separately, 2026-11-25): round-0 prompt hashes (system prompt + observation) "
          "are identical between v1.0 B and v1.1 B in all 10 seeds; `tests/test_v1_identity.py` passes; the Adaption "
          "call sends the same arguments. Decoy problems and board lines differ because they depend on which "
          "problems are still open and, in v1.0, on the decoy-line history shared by concurrent runs.", "",
          "No run log records a model version or fingerprint from the API, so a change in the hosted model between "
          "dates cannot be checked from the logs."]
    out = R / "analysis/v1.1/diag_v10code_B.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()

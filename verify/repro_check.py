#!/usr/bin/env python3
"""v1.1 reproducibility check: compare a re-run of B seed 0 with the original and with all 20 v1.0 B runs.

Metric definitions follow v1.0 (analysis/exploratory.md section 11): first verdict per (honest agent,
entry), flag = "exploit" verdict, entries classed by author. Sanity check: reproduces the published
v1.0 B pooled first-verdict counts (decoy 36/137, cheater 69/203, seeds 0-9).

Usage (from repo root): python verify/repro_check.py [runs/v1.1/repro_check/B_seed0/events.jsonl]
Writes analysis/v1.1/repro_check.md.
"""
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from swarm.config import CHEATER_NAMES, HONEST_LLM_NAMES, SEED_AGENT_NAMES  # noqa: E402

CH, HO, DE = set(CHEATER_NAMES), set(HONEST_LLM_NAMES), set(SEED_AGENT_NAMES)
CATS = ("cheater", "decoy", "honest")


def metrics(path: Path) -> dict:
    ev = [json.loads(l) for l in open(path)]
    owner = {e["payload"]["entry_id"]: e["agent"] for e in ev
             if e["type"] == "submit" and e["payload"].get("accepted")}

    def cat(eid):
        a = owner.get(eid)
        return "cheater" if a in CH else "decoy" if a in DE else "honest" if a in HO else None

    first: dict = {}
    for e in ev:  # events are in round order, so setdefault keeps the earliest verdict
        if e["type"] == "review" and e["agent"] in HO:
            eid = e["payload"]["entry_id"]
            c = cat(eid)
            if c is not None:
                first.setdefault((e["agent"], eid), (c, e["payload"]["verdict"]))
    fv = {c: [0, 0] for c in CATS}
    for c, v in first.values():
        fv[c][1] += 1
        fv[c][0] += v == "exploit"
    revs = [e["payload"]["entry_id"] for e in ev if e["type"] == "revocation"]
    meta = next(e["payload"] for e in ev if e["type"] == "run_meta")
    summ = next((e["payload"] for e in ev if e["type"] == "run_summary"), {})
    return {
        "fv": fv,
        "rev": len(revs), "rev_cheater": sum(cat(r) == "cheater" for r in revs),
        "rev_decoy": sum(cat(r) == "decoy" for r in revs), "rev_honest": sum(cat(r) == "honest" for r in revs),
        "reports": sum(e["type"] == "report" for e in ev),
        "parse_fail": sum(e["type"] == "parse_fail" for e in ev),
        "n_cheater": sum(a in CH for a in owner.values()),
        "git": meta["git_hash"][:7], "run_id": meta["run_id"],
        "credits": summ.get("total_credits"), "retries": summ.get("retry_count"),
    }


def pct(a):
    return f"{100 * a[0] / a[1]:.1f}% ({a[0]}/{a[1]})" if a[1] else "N/A"


def rate(a):
    return a[0] / a[1] if a[1] else None


def main() -> None:
    repro_path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "runs/v1.1/repro_check/B_seed0/events.jsonl"
    b = {}
    for s in range(20):
        p = ROOT / (f"runs/real/B_seed{s}" if s < 10 else f"runs/followup/qwen_B_seed{s}") / "events.jsonl"
        b[s] = metrics(p)
    rep = metrics(repro_path)
    orig = b[0]

    # Sanity check against published v1.0 numbers
    pooled = {c: [sum(b[s]["fv"][c][i] for s in range(10)) for i in (0, 1)] for c in CATS}
    sane = pooled["decoy"] == [36, 137] and pooled["cheater"] == [69, 203]

    specs = [
        ("Decoy first-verdict flag rate", lambda m: rate(m["fv"]["decoy"]), lambda m: pct(m["fv"]["decoy"]), True),
        ("Cheater first-verdict flag rate", lambda m: rate(m["fv"]["cheater"]), lambda m: pct(m["fv"]["cheater"]), True),
        ("Honest first-verdict flag rate", lambda m: rate(m["fv"]["honest"]), lambda m: pct(m["fv"]["honest"]), True),
        ("Revocations (total)", lambda m: m["rev"], lambda m: str(m["rev"]), False),
        ("Revocations of cheater entries", lambda m: m["rev_cheater"], lambda m: str(m["rev_cheater"]), False),
        ("Revocations of decoy entries", lambda m: m["rev_decoy"], lambda m: str(m["rev_decoy"]), False),
        ("Revocations of honest entries", lambda m: m["rev_honest"], lambda m: str(m["rev_honest"]), False),
        ("Cheater entries", lambda m: m["n_cheater"], lambda m: str(m["n_cheater"]), False),
        ("Reports filed", lambda m: m["reports"], lambda m: str(m["reports"]), False),
        ("Parse failures", lambda m: m["parse_fail"], lambda m: str(m["parse_fail"]), False),
    ]
    L = [
        "# v1.1 reproducibility check: B, seed 0",
        "",
        "Generated by `verify/repro_check.py`. Re-run of setup B, seed 0, with the same settings as the sprint",
        "(qwen3.5-397b, 20 rounds, temperature 0.7, max_output_tokens 1500, 8 LLM agents + 2 decoys). No code was",
        "changed to make results match.",
        "",
        f"- Original: `runs/real/B_seed0` (run `{orig['run_id']}`, commit `{orig['git']}`)",
        f"- Re-run: `{repro_path.relative_to(ROOT) if repro_path.is_absolute() else repro_path}` "
        f"(run `{rep['run_id']}`, commit `{rep['git']}`; {rep['credits']:.3f} credits, {rep['retries']} retries)",
        f"- Code differences between the two commits only add condition D; the B code path is unchanged.",
        f"- Sanity check: this script reproduces the published v1.0 B pooled first-verdict counts "
        f"(decoy {pooled['decoy'][0]}/{pooled['decoy'][1]}, cheater {pooled['cheater'][0]}/{pooled['cheater'][1]}): "
        f"**{'PASS' if sane else 'FAIL'}**",
        "",
        "Spread = the 20 v1.0 B runs (seeds 0-9 main, 10-19 follow-up). Percentile = share of those 20 runs below the "
        "re-run value (ties count half).",
        "",
        "| Metric | Original s0 | Re-run s0 | v1.0 B min | median | max | mean (sd) | Re-run percentile |",
        "|---|---|---|---|---|---|---|---|",
    ]
    in_range = []
    for name, f, show, is_rate in specs:
        vals = [v for v in (f(b[s]) for s in range(20)) if v is not None]
        rv = f(rep)
        k = 100 if is_rate else 1
        fmt = (lambda x: f"{k * x:.1f}%") if is_rate else (lambda x: f"{x:.2f}".rstrip("0").rstrip("."))
        in_range.append(min(vals) <= rv <= max(vals))
        perc = 100 * (sum(v < rv for v in vals) + 0.5 * sum(v == rv for v in vals)) / len(vals)
        L.append(f"| {name} | {show(orig)} | {show(rep)} | {fmt(min(vals))} | {fmt(statistics.median(vals))} | "
                 f"{fmt(max(vals))} | {fmt(statistics.mean(vals))} ({fmt(statistics.stdev(vals))}) | {perc:.0f} |")
    L += [
        "",
        "## Reading",
        "",
        "- The re-run does not match the original exactly. This is expected: the seed fixes only scripted parts",
        "  (puzzle order, decoy schedule, CA draws), not model outputs, which are sampled at temperature 0.7.",
        f"- Re-run metrics within the min-max range of the 20 v1.0 B runs: {sum(in_range)}/{len(in_range)}.",
        "- The largest change is the decoy first-verdict flag rate. The original seed-0 value was the lowest of all",
        "  20 B runs, so a re-run landing higher is what regression to the mean predicts.",
        "- Implication: paired seeds behave almost like independent runs; see `PREREG_v1.1.md`, Seeds.",
        "",
        "## Per-run table (v1.0 B seeds 0-19 and re-run)",
        "",
        "| Run | Cheater entries | Decoy 1st flag | Cheater 1st flag | Honest 1st flag | Revocations tot/cheater/decoy/honest | Reports | Parse fails |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for label, m in [(f"B seed {s}", b[s]) for s in range(20)] + [("**Re-run seed 0**", rep)]:
        L.append(f"| {label} | {m['n_cheater']} | {pct(m['fv']['decoy'])} | {pct(m['fv']['cheater'])} | "
                 f"{pct(m['fv']['honest'])} | {m['rev']}/{m['rev_cheater']}/{m['rev_decoy']}/{m['rev_honest']} | "
                 f"{m['reports']} | {m['parse_fail']} |")
    out = ROOT / "analysis/v1.1/repro_check.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
